std::shared_ptr<Media::PixelMap> CreateTestPixelMap(int32_t width, int32_t height)
{
    if (width <= 0 || height <= 0) {
        std::cout << "CreateTestPixelMap: invalid size" << std::endl;
        return nullptr;
    }

    const int32_t bytesPerPixel = 4;
    const size_t dataSize = static_cast<size_t>(width) * height * bytesPerPixel;
    auto data = std::make_unique<uint8_t[]>(dataSize);

    // Mixed pattern: left half = color gradient, right half = B/W checkerboard
    const int32_t halfW = width / WIDTH_SPLIT_RATIO;
    for (int32_t y = 0; y < height; y++) {
        for (int32_t x = 0; x < width; x++) {
            const size_t idx = (static_cast<size_t>(y) * width + x) * bytesPerPixel;
            if (x < halfW) {
                data[idx + RGBA_CHANNEL_R] = static_cast<uint8_t>(COLOR_FULL_SCALE * y / std::max(height, 1));
                data[idx + RGBA_CHANNEL_G] = static_cast<uint8_t>(COLOR_FULL_SCALE * x / halfW);
                data[idx + RGBA_CHANNEL_B] =
                    static_cast<uint8_t>(COLOR_FULL_SCALE - COLOR_FULL_SCALE * y / std::max(height, 1));
            } else {
                const int32_t bx = (x - halfW) / CHECKERBOARD_CELL_SIZE;
                const int32_t by = y / CHECKERBOARD_CELL_SIZE;
                const uint8_t v = ((bx + by) % CHECKERBOARD_PARITY == 0) ? COLOR_FULL_SCALE : 0;
                data[idx + RGBA_CHANNEL_R] = v;
                data[idx + RGBA_CHANNEL_G] = v;
                data[idx + RGBA_CHANNEL_B] = v;
            }
            data[idx + RGBA_CHANNEL_A] = COLOR_FULL_SCALE;
        }
    }

    Media::InitializationOptions opts;
    opts.size.width = width;
    opts.size.height = height;
    opts.pixelFormat = Media::PixelFormat::RGBA_8888;
    opts.alphaType = OHOS::Media::AlphaType::IMAGE_ALPHA_TYPE_OPAQUE;
    opts.editable = true;

    auto pixelmap = Media::PixelMap::Create(
        reinterpret_cast<const uint32_t*>(data.get()), dataSize, opts);
    if (pixelmap == nullptr) {
        std::cout << "CreateTestPixelMap: PixelMap::Create failed" << std::endl;
        return nullptr;
    }
    return pixelmap;
}

std::shared_ptr<RSNGDistortLightFilter> CreateDefaultDistortLightFilter()
{
    auto distortLightFilter = std::make_shared<RSNGDistortLightFilter>();
    if (!distortLightFilter) {
        return nullptr;
    }
    auto rippleMask = std::make_shared<RSNGRippleMask>();
    if (rippleMask) {
        rippleMask->Setter<RippleMaskCenterTag>(Vector2f(0.5f, 0.5f));
        rippleMask->Setter<RippleMaskRadiusTag>(0.5f);
        rippleMask->Setter<RippleMaskWidthTag>(0.5f);
        rippleMask->Setter<RippleMaskOffsetTag>(0.0f);
        distortLightFilter->Setter<DistortLightDistortMaskTag>(std::static_pointer_cast<RSNGMaskBase>(rippleMask));
    }
    distortLightFilter->Setter<DistortLightLightFactorTag>(0.5f);
    distortLightFilter->Setter<DistortLightHighLightFactorTag>(1.0f);
    distortLightFilter->Setter<DistortLightHighLightWidthTag>(0.2f);
    distortLightFilter->Setter<DistortLightHighLightSoftTag>(0.1f);
    distortLightFilter->Setter<DistortLightHighLightColorTag>(Vector4f{1.0f, 1.0f, 1.0f, 1.0f});
    return distortLightFilter;
}

